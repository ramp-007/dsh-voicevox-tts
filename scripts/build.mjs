// Host (ESM) と Client (DSH のモジュールローダー形式) をバンドルして lib/ に出力する。
import { build } from 'esbuild'
import { mkdir, readFile, writeFile } from 'node:fs/promises'

const pkg = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'))

await mkdir('lib', { recursive: true })

await build({
  entryPoints: ['src/host/index.ts'],
  outfile: 'lib/index.js',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node24',
  legalComments: 'none',
})

// Client は iife にして、DSH の遅延ローダー(window.__ModuleLoader__)の factory に包む。
// react はプラットフォームが供給するので外部扱い（factory の require で解決される）。
const client = await build({
  entryPoints: ['src/client/index.ts'],
  write: false,
  bundle: true,
  platform: 'browser',
  format: 'iife',
  globalName: '__dshVoicevoxTts',
  target: 'es2022',
  external: ['react'],
  legalComments: 'none',
})
const body = client.outputFiles[0].text
const wrapped = `// ${pkg.name} ${pkg.version} - client half (generated by scripts/build.mjs; do not edit)
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory: require => {
    ${body}
    return __dshVoicevoxTts;
  },
});
`
await writeFile('lib/client.js', wrapped, 'utf8')
console.log('built lib/index.js and lib/client.js')
